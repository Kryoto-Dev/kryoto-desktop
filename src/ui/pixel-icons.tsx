/**
 * Kryoto's icons, in two styles the reader picks between (Appearance, Icons):
 *
 * - **Pixel** (the default): pixel art on a 12 by 12 grid, in the same blocky
 *   cells as the ASCII motion and the badges. At the common 14 px size every
 *   cell is exactly one pixel; other sizes snap to whole pixels too. Hovering
 *   or focusing the button or link around an icon plays a short animation
 *   (`pixel-icons-motion.tsx`): the icon's own story where it has one (`ANIM`),
 *   otherwise a rain of bright cells down its columns, matrix-style. With
 *   reduced motion it is the still picture, always.
 * - **Classic**: the line icons Kryoto used before, for anyone who finds the
 *   pixels harder to read.
 *
 * Every icon's SVG carries the pixel picture and a `<use>` of its classic one.
 * `data-icons="classic"` on <html> (`lib/icon-style.ts` stamps it before first
 * paint) makes `pixel-icons-motion.tsx` load the classic shapes
 * (`pixel-icons-classic.ts`) into one sprite on the page, and CSS shows the
 * classic pictures once it is there. Readers on Pixel never download them.
 *
 * Names and props match lucide-react's, so call sites read the same:
 * `<Download className="size-3.5" />`. `size`, `color`, `className` and
 * `strokeWidth` (Classic) work; a `fill-*` class picks the filled picture
 * where an icon has one (a rated star, a liked heart); `animate-spin` turns a
 * pixel icon in quarter steps and a classic one smoothly.
 *
 * Art legend: `#` a cell, `+` a dim cell, `.` empty; 12 rows of 12.
 *
 * THE SAME FILE LIVES IN EVERY KRYOTO FRONTEND. The copy in kryo.to
 * (`components/pixel-icons.tsx`) is the source: `pnpm sync:pixel-icons` copies
 * it and the motion file into the other apps, and `pnpm check:pixel-icons`
 * fails when a copy has drifted. The Classic shapes are Lucide's, with their
 * license, in `pixel-icons-classic.ts`.
 */

import type { CSSProperties, ReactElement, SVGProps } from 'react'

/** Twelve rows of twelve cells, rows separated by spaces. */
type Art = string
/** A block of cells: `[x, y, width, height]`. */
type Rect = [number, number, number, number]

export type IconAnim =
  /** Slide by a cell and back, twice; `fix` blocks stay put. */
  | { k: 'nudge'; x: number; y: number; fix?: Rect[] }
  /** Side to side a few times: a ring, a shiver. */
  | { k: 'shake'; x: number; y: number; fix?: Rect[] }
  /** The picture draws itself in from one side. */
  | { k: 'draw'; o: 'ltr' | 'rtl' | 'ttb' | 'btt' | 'out' }
  /** A full turn in quarter steps. */
  | { k: 'spin'; ccw?: boolean }
  /** A line sweeps down through the picture, flipping its cells. */
  | { k: 'scan' }
  /** The filled picture flashes in. */
  | { k: 'fill' }
  /** The cells dim and come back. */
  | { k: 'pulse' }
  /** Shut and open again, as an eye blinks. */
  | { k: 'shut' }
  /** Some blocks go out and come back. */
  | { k: 'blink'; off: Rect[] }
  /** Some blocks light up and go out. */
  | { k: 'flash'; on: Rect[] }
  /** Hand-drawn frames, then the still picture. */
  | { k: 'frames'; f: Art[]; step?: number }

