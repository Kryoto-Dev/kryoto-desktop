export type LucideProps = Omit<SVGProps<SVGSVGElement>, 'stroke' | 'strokeWidth'> & {
  size?: number | string
  color?: string
  strokeWidth?: number | string
  absoluteStrokeWidth?: boolean
  title?: string
}
export type LucideIcon = ((props: LucideProps) => ReactElement) & { displayName?: string }
export type PixelIcon = LucideIcon

const SPIN = /(^|\s)animate-spin(?=\s|$)/g
const HAS_SPIN = /(^|\s)animate-spin(\s|$)/
const FILL = /(^|\s)fill-(?!none(\s|$))[\w-]+/

function makeIcon(name: PixelIconName, classic: string): LucideIcon {
  const Icon = ({
    size,
    color,
    className,
    style,
    strokeWidth = 2,
    absoluteStrokeWidth: _absolute,
    title,
    children,
    ...rest
  }: LucideProps) => {
    let classes = className ?? ''
    let loop: string | undefined = LOOPING.has(name) ? 'loop' : undefined
    if (HAS_SPIN.test(classes)) {
      classes = classes.replace(SPIN, ' ') + ' kp-spin'
      loop = loop ?? 'spin'
    }
    const filled = FILL.test(classes) ? FILLED[name] : undefined
    const [full, dim] = artPaths(filled ?? ART[name])
    const offset = artOffset(ART[name])
    const labelled = Boolean(rest['aria-label'] || rest['aria-labelledby'] || title)
    const sized = size ?? 24
    const merged: CSSProperties | undefined = color ? { ...style, color } : style
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 24 24"
        width={sized}
        height={sized}
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden={labelled ? undefined : true}
        role={labelled ? 'img' : undefined}
        focusable="false"
        {...rest}
        className={`kp-icon ${classes}`.trim().replace(/\s+/g, ' ')}
        style={merged}
        data-kp={name}
        data-kp-filled={filled ? '' : undefined}
        data-kp-loop={loop}
      >
        {title ? <title>{title}</title> : null}
        {/* suppressHydrationWarning: pixel-icons-motion.tsx fits this viewBox to the
            device pixels as soon as the icon is in the page, which for streamed
            HTML can be before React hydrates it. */}
        <svg suppressHydrationWarning className="kp-p" viewBox={pixelViewBox(boxOf(size, classes), offset)} data-kp-o={offset[0] || offset[1] ? offset.join(' ') : undefined} width="24" height="24" fill="currentColor" stroke="none" shapeRendering="crispEdges">
          <path d={full} />
          <path d={dim} opacity={0.45} />
        </svg>
        {/* The classic picture, from the sprite pixel-icons-motion.tsx adds in the Classic style. */}
        <use className="kp-l" display="none" href={`#kp-c-${classic}`} />
        {children}
      </svg>
    )
  }
  Icon.displayName = name
  return Icon
}

