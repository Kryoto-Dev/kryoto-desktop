export const GRID = 12

/** `#` → 2, `+` → 1, anything else → 0. */
export function parseArt(art: Art): number[][] {
  const rows = art.trim().split(/\s+/)
  return Array.from({ length: GRID }, (_, y) =>
    Array.from({ length: GRID }, (_, x) => {
      const c = rows[y]?.[x]
      return c === '#' ? 2 : c === '+' ? 1 : 0
    }),
  )
}

/** One path per tone, each row's runs merged: `[full, dim]`. */
export function gridPaths(grid: number[][]): [string, string] {
  const out: [string, string] = ['', '']
  grid.forEach((row, y) => {
    for (const tone of [2, 1] as const) {
      let x = 0
      while (x < row.length) {
        if (row[x] !== tone) {
          x++
          continue
        }
        const start = x
        while (x < row.length && row[x] === tone) x++
        out[tone === 2 ? 0 : 1] += `M${start} ${y}h${x - start}v1h-${x - start}z`
      }
    }
  })
  return out
}

// `globalThis.Map`: this module exports an icon called `Map`.
const pathCache = new globalThis.Map<string, [string, string]>()
export function artPaths(art: Art): [string, string] {
  let hit = pathCache.get(art)
  if (!hit) {
    hit = gridPaths(parseArt(art))
    pathCache.set(art, hit)
  }
  return hit
}

const offsetCache = new globalThis.Map<string, [number, number]>()
/**
 * How far a picture's drawn cells sit from the grid's centre, in cells. The
 * grid is 12 across, so its centre falls between two cells, and a drawing an
 * odd number of cells wide (a 1-cell arrow shaft, a chevron, a plus) can only
 * sit half a cell to one side. Drawn with this offset, every picture is
 * centred on what it shows.
 */
export function artOffset(art: Art): [number, number] {
  let hit = offsetCache.get(art)
  if (!hit) {
    let x0 = GRID, x1 = -1, y0 = GRID, y1 = -1
    parseArt(art).forEach((row, y) =>
      row.forEach((v, x) => {
        if (!v) return
        x0 = Math.min(x0, x)
        x1 = Math.max(x1, x)
        y0 = Math.min(y0, y)
        y1 = Math.max(y1, y)
      }),
    )
    hit = x1 < 0 ? [0, 0] : [(x0 + x1 + 1) / 2 - GRID / 2, (y0 + y1 + 1) / 2 - GRID / 2]
    offsetCache.set(art, hit)
  }
  return hit
}

/** Tailwind's size steps, so a `size-3.5` icon knows it is 14 px across. */
const STEP = /(?:^|\s)(?:size|h|w)-(\d+(?:\.5)?)(?=\s|$)/
const PX = /(?:^|\s)(?:size|h|w)-\[(\d+(?:\.\d+)?)px\](?=\s|$)/

function boxOf(size: number | string | undefined, className: string): number | undefined {
  if (typeof size === 'number') return size
  if (typeof size === 'string' && /^\d+(\.\d+)?(px)?$/.test(size)) return parseFloat(size)
  const px = className.match(PX)
  if (px?.[1]) return parseFloat(px[1])
  const step = className.match(STEP)
  if (step?.[1]) return parseFloat(step[1]) * 4
  return size === undefined ? 24 : undefined
}

/**
 * The pixel picture's viewBox for a box of `px` pixels: whole pixels per
 * cell, the nearest fit (1 up to 17 px, 2 from 18, 3 from 29...), and the
 * picture centred, so its edges never fall between two screen pixels. The
 * page re-fits it to the screen's real device pixels with the same rule
 * (`snapIcon` in `pixel-icons-motion.tsx`).
 */
export function pixelViewBox(px: number | undefined, [dx, dy]: [number, number] = [0, 0]): string {
  if (!px) return `${dx} ${dy} ${GRID} ${GRID}`
  // Never under one pixel a cell; a slightly bigger grid spills only its empty margin past the box.
  const cell = Math.max(1, Math.round(px / 11.5))
  const span = px / cell
  const pad = (span - GRID) / 2
  return `${dx - pad} ${dy - pad} ${span} ${span}`
}

