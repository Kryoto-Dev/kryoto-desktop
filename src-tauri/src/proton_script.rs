//! A launcher alongside Linux installs, usable by Play and from a terminal.
use crate::launch::{self, LaunchPlan};
use std::path::{Path, PathBuf};

const HEADER: &str = "#!/bin/sh\n# Generated by Kryoto: run_proton.sh\n";

fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

pub fn write(
    root: &Path,
    executable: &str,
    args: &str,
    prefix: &Path,
    env: &[(String, String)],
    umu: Option<&Path>,
) -> Result<PathBuf, String> {
    let script = root.join("run_proton.sh");
    // A release's own launcher or a player's replacement belongs to them.
    if script.exists() {
        let existing = std::fs::read_to_string(&script)
            .map_err(|e| format!("Could not read run_proton.sh: {e}"))?;
        if !existing.starts_with(HEADER) {
            return Ok(script);
        }
    }
    let exe = launch::inside(root, executable)?;
    let relative = exe
        .strip_prefix(root)
        .map_err(|e| e.to_string())?
        .to_string_lossy()
        .replace('\\', "/");
    let existing_prefix = prefix.join("pfx");
    let prefix = if existing_prefix.is_dir() {
        &existing_prefix
    } else {
        prefix
    };
    let mut defaults = vec![
        (
            "WINEPREFIX".to_string(),
            prefix.to_string_lossy().into_owned(),
        ),
        ("PROTONPATH".to_string(), "GE-Proton".to_string()),
        ("GAMEID".to_string(), "umu-default".to_string()),
    ];
    for (key, value) in env {
        if let Some(slot) = defaults.iter_mut().find(|(k, _)| k == key) {
            slot.1 = value.clone();
        } else {
            defaults.push((key.clone(), value.clone()));
        }
    }
    let mut content = HEADER.to_string();
    content.push_str("# Settings > Compatibility installs Proton and its runtime.\n# Environment overrides and extra arguments are welcome.\nset -eu\n");
    for (key, value) in defaults {
        // These names are produced by the launch planner, never shell source.
        if key.is_empty()
            || !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
            || key.starts_with(|c: char| c.is_ascii_digit())
        {
            continue;
        }
        content.push_str(&format!(
            "if [ -z \"${{{key}:-}}\" ]; then {key}={}; fi\nexport {key}\n",
            quote(&value)
        ));
    }
    content.push_str("script_dir=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\n");
    content.push_str(&format!("default_exe=\"$script_dir\"/{}\ndefault_cwd=$(dirname -- \"$default_exe\")\ndefault_umu={}\n", quote(&relative), quote(&umu.map(|p| p.to_string_lossy().into_owned()).unwrap_or_else(|| "umu-run".into()))));
    content.push_str("exe=${KRYOTO_EXECUTABLE:-$default_exe}\ncwd=${KRYOTO_WORKING_DIR:-$default_cwd}\nrunner=${KRYOTO_UMU_RUN:-$default_umu}\n");
    content.push_str("if [ ! -f \"$exe\" ]; then printf '%s\\n' \"Game executable is missing: $exe\" >&2; exit 1; fi\n");
    content.push_str("if ! command -v \"$runner\" >/dev/null 2>&1; then printf '%s\\n' 'Install Proton and its runtime in Kryoto Settings > Compatibility, or install umu-run.' >&2; exit 1; fi\n");
    content.push_str("mkdir -p -- \"$WINEPREFIX\"\ncd -- \"$cwd\"\nif [ \"${1-}\" = '--kryoto-launch' ]; then\n  shift\nelse\n  set --");
    for arg in launch::split_words(args) {
        content.push(' ');
        content.push_str(&quote(&arg));
    }
    content.push_str(" \"$@\"\nfi\nexec \"$runner\" \"$exe\" \"$@\"\n");
    if std::fs::read_to_string(&script).ok().as_deref() != Some(&content) {
        std::fs::write(&script, content)
            .map_err(|e| format!("Could not write run_proton.sh: {e}"))?;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755))
            .map_err(|e| e.to_string())?;
    }
    Ok(script)
}

/// Keep wrappers, game arguments, environment and process tracking in the plan.
#[cfg_attr(not(target_os = "linux"), allow(dead_code))]
pub fn use_script(plan: &mut LaunchPlan, script: &Path) -> Result<(), String> {
    let mut chain = vec![plan.program.to_string_lossy().into_owned()];
    chain.extend(plan.lead_args.clone());
    if chain.pop().as_deref() != Some(plan.exe.to_string_lossy().as_ref()) {
        return Err("The Proton launch command is missing its executable.".into());
    }
    let runner = chain
        .pop()
        .ok_or("The Proton launch command is missing its runtime.")?;
    chain.extend(["/bin/sh".into(), script.to_string_lossy().into_owned()]);
    if std::fs::read_to_string(script)
        .map(|s| s.starts_with(HEADER))
        .unwrap_or(true)
    {
        chain.push("--kryoto-launch".into());
    }
    plan.program = PathBuf::from(chain.remove(0));
    plan.lead_args = chain;
    plan.env.extend([
        (
            "KRYOTO_EXECUTABLE".into(),
            plan.exe.to_string_lossy().into_owned(),
        ),
        (
            "KRYOTO_WORKING_DIR".into(),
            plan.cwd.to_string_lossy().into_owned(),
        ),
        ("KRYOTO_UMU_RUN".into(), runner),
    ]);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn quotes_shell_metacharacters_and_keeps_custom_scripts() {
        assert_eq!(quote("a'b $()"), "'a'\\''b $()'");
        let root =
            std::env::temp_dir().join(format!("kryoto-proton-script-{}", std::process::id()));
        std::fs::create_dir_all(&root).unwrap();
        let path = write(
            &root,
            "Game.exe",
            "--profile 'My save'",
            &root.join("prefix"),
            &[],
            None,
        )
        .unwrap();
        let script = std::fs::read_to_string(&path).unwrap();
        assert!(script.contains("set -- '--profile' 'My save' \"$@\""));
        assert!(script.contains("exec \"$runner\" \"$exe\" \"$@\""));
        std::fs::write(&path, "#!/bin/sh\n# custom\n").unwrap();
        write(&root, "Other.exe", "", &root.join("prefix"), &[], None).unwrap();
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            "#!/bin/sh\n# custom\n"
        );
        std::fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn app_wrappers_and_arguments_survive() {
        let mut plan = LaunchPlan {
            program: "gamemoderun".into(),
            lead_args: vec![
                "mangohud".into(),
                "/tools/umu-run".into(),
                "/games/Game.exe".into(),
            ],
            exe: "/games/Game.exe".into(),
            cwd: "/games".into(),
            game_args: "--profile 'My save'".into(),
            env: vec![("WINEPREFIX".into(), "/saved/pfx".into())],
        };
        use_script(&mut plan, Path::new("/games/run_proton.sh")).unwrap();
        assert_eq!(plan.program, Path::new("gamemoderun"));
        assert_eq!(
            plan.lead_args,
            [
                "mangohud",
                "/bin/sh",
                "/games/run_proton.sh",
                "--kryoto-launch"
            ]
        );
        assert_eq!(plan.game_args, "--profile 'My save'");
        assert!(plan
            .env
            .contains(&("WINEPREFIX".into(), "/saved/pfx".into())));
    }

    fn execute_launcher() {
        let shell = std::env::var("KRYOTO_TEST_SH").unwrap_or_else(|_| "sh".into());
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let root = std::env::temp_dir().join(format!("kryoto proton 'quoted' {stamp}"));
        let prefix = root.join("saved-prefix");
        std::fs::create_dir_all(root.join("bin")).unwrap();
        std::fs::create_dir_all(prefix.join("pfx")).unwrap();
        std::fs::write(prefix.join("pfx/save.dat"), "existing save").unwrap();
        std::fs::write(root.join("bin/My Game.exe"), "fixture").unwrap();
        let runner = root.join("umu-run");
        std::fs::write(&runner, "#!/bin/sh\nprintf '%s\\n' \"$WINEPREFIX\" \"$PROTONPATH\" \"$GAMEID\" \"$WINEDLLOVERRIDES\" \"$PWD\" \"$@\" > \"$KRYOTO_TEST_LOG\"\n").unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&runner, std::fs::Permissions::from_mode(0o755)).unwrap();
        }
        let path_text = |p: &Path| p.to_string_lossy().replace('\\', "/");
        let env = vec![
            ("PROTONPATH".into(), "Tool $() 'quoted'".into()),
            ("WINEDLLOVERRIDES".into(), "steam_api=n,b".into()),
        ];
        let script = write(
            &root,
            "bin/My Game.exe",
            "--profile 'My save' --literal '$()'",
            &prefix,
            &env,
            Some(Path::new(&path_text(&runner))),
        )
        .unwrap();
        let log = root.join("launch.log");
        let run = |args: &[&str]| {
            let mut command = std::process::Command::new(&shell);
            command
                .arg(path_text(&script))
                .args(args)
                .env("KRYOTO_TEST_LOG", path_text(&log));
            command.output().unwrap()
        };
        let output = run(&["extra argument"]);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let text = std::fs::read_to_string(&log).unwrap().replace('\\', "/");
        assert!(text.contains("saved-prefix/pfx\nTool $() 'quoted'\numu-default\nsteam_api=n,b\n"));
        assert!(
            text.ends_with("bin/My Game.exe\n--profile\nMy save\n--literal\n$()\nextra argument\n"),
            "{text}"
        );
        let output = run(&["--kryoto-launch", "--entry", "Selected entry"]);
        assert!(output.status.success());
        let text = std::fs::read_to_string(&log).unwrap();
        assert!(text.ends_with("bin/My Game.exe\n--entry\nSelected entry\n"));
        assert!(
            !text.contains("My save"),
            "app arguments are not duplicated with defaults"
        );
        assert_eq!(
            std::fs::read_to_string(prefix.join("pfx/save.dat")).unwrap(),
            "existing save"
        );
        // Moving the installation does not leave the executable pointing at the old folder.
        let moved = root.with_file_name(format!("kryoto moved {stamp}"));
        std::fs::rename(&root, &moved).unwrap();
        let output = std::process::Command::new(&shell)
            .arg(path_text(&moved.join("run_proton.sh")))
            .env("KRYOTO_UMU_RUN", path_text(&moved.join("umu-run")))
            .env("WINEPREFIX", path_text(&moved.join("saved-prefix/pfx")))
            .env("KRYOTO_TEST_LOG", path_text(&moved.join("launch.log")))
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let output = std::process::Command::new(&shell)
            .arg(path_text(&moved.join("run_proton.sh")))
            .env("KRYOTO_UMU_RUN", "missing-kryoto-test-runtime")
            .output()
            .unwrap();
        assert!(!output.status.success());
        assert!(String::from_utf8_lossy(&output.stderr).contains("Settings > Compatibility"));
        std::fs::remove_dir_all(moved).unwrap();
    }

    #[cfg(unix)]
    #[test]
    fn real_shell_preserves_arguments_environment_saves_and_moved_installs() {
        execute_launcher();
    }

    #[cfg(windows)]
    #[test]
    #[ignore = "Set KRYOTO_TEST_SH to a POSIX shell and run explicitly"]
    fn real_shell_preserves_arguments_environment_saves_and_moved_installs() {
        execute_launcher();
    }
}
