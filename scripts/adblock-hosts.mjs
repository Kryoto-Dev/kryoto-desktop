// Builds src-tauri/resources/adblock/hosts.txt, the host list the built-in
// browser blocks by (src-tauri/src/adblock.rs), from the filter lists bundled
// with uBlock Origin (src-tauri/resources/ublock/assets).
//
// Only what a request filter can do natively is kept: `||host^` rules, with
// `$third-party` where the list says so, and `@@||host^` exceptions. Cosmetic
// rules and scriptlets need a script in the page, which Kryoto never puts
// there (a page script breaks Cloudflare's check on every download).
//
//   node scripts/adblock-hosts.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src-tauri', 'resources')
const assets = join(root, 'ublock', 'assets')
const LISTS = ['thirdparties/easylist/easylist.txt', 'ublock/filters.min.txt', 'ublock/badware.min.txt', 'ublock/unbreak.min.txt']
const HOSTS = 'thirdparties/pgl.yoyo.org/as/serverlist'

const HOST = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/
// Options that only narrow which kinds of request a rule is about. A block
// rule with one of these is left out (blocking every kind would break pages);
// an exception with them is kept for every kind (letting a little more
// through is the safe side).
const TYPES = new Set(['script', 'image', 'stylesheet', 'css', 'xhr', 'xmlhttprequest', 'frame', 'subdocument', 'media', 'font', 'object', 'ping', 'websocket', 'other', 'all', 'important', '~third-party', '1p', 'first-party'])

const block = new Set()
const thirdParty = new Set()
const allow = new Set()

function rule(line) {
  const exception = line.startsWith('@@')
  const body = exception ? line.slice(2) : line
  const m = /^\|\|([a-z0-9.-]+)\^(?:\$(.*))?$/.exec(body)
  if (!m || !HOST.test(m[1])) return
  const host = m[1]
  const options = m[2] ? m[2].split(',') : []
  if (exception) {
    if (options.every((o) => TYPES.has(o))) allow.add(host)
    return
  }
  const rest = options.filter((o) => o !== 'important' && o !== 'all')
  if (rest.length === 0) block.add(host)
  else if (rest.length === 1 && (rest[0] === 'third-party' || rest[0] === '3p')) thirdParty.add(host)
}

for (const list of LISTS) {
  for (const raw of readFileSync(join(assets, list), 'utf8').split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('!') || line.startsWith('[') || line.includes('#')) continue
    rule(line)
  }
}
for (const raw of readFileSync(join(assets, HOSTS), 'utf8').split(/\r?\n/)) {
  const host = raw.trim().split(/\s+/)[1]
  if (host && HOST.test(host)) block.add(host)
}

// A host blocked outright needs no third-party line; a parent already blocked
// covers its subdomains.
const covered = (host) => {
  for (let at = host.indexOf('.'); at !== -1; at = host.indexOf('.', at + 1)) {
    if (block.has(host.slice(at + 1))) return true
  }
  return false
}
const lines = [
  '# Hosts the built-in browser blocks (src-tauri/src/adblock.rs).',
  '# Generated by scripts/adblock-hosts.mjs from uBlock Origin\'s bundled lists:',
  `# ${[...LISTS, HOSTS].join(', ')}.`,
  '# `host` blocks it and its subdomains, `host 3p` only from other sites, `@@host` never.',
  ...[...block].filter((h) => !covered(h)).sort(),
  ...[...thirdParty].filter((h) => !block.has(h) && !covered(h)).sort().map((h) => `${h} 3p`),
  ...[...allow].sort().map((h) => `@@${h}`),
]
mkdirSync(join(root, 'adblock'), { recursive: true })
writeFileSync(join(root, 'adblock', 'hosts.txt'), lines.join('\n') + '\n')
console.log(`adblock: ${block.size} blocked, ${thirdParty.size} third-party, ${allow.size} allowed`)
